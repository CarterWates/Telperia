-- Phase 6 result ingestion draft.
-- This migration is committed for review only and has not been applied to a live Supabase project.
-- It defines private-by-default result uploads, extracted summaries, public review state, and raw JSON Storage.

do $$
begin
  if not exists (select 1 from pg_type where typname = 'result_visibility' and typnamespace = 'public'::regnamespace) then
    create type public.result_visibility as enum ('private', 'submitted_for_public_review', 'public');
  end if;

  if not exists (select 1 from pg_type where typname = 'ingestion_status' and typnamespace = 'public'::regnamespace) then
    create type public.ingestion_status as enum ('pending', 'accepted', 'rejected');
  end if;

  if not exists (select 1 from pg_type where typname = 'public_submission_status' and typnamespace = 'public'::regnamespace) then
    create type public.public_submission_status as enum ('pending_review', 'approved', 'rejected');
  end if;

  if not exists (select 1 from pg_type where typname = 'local_ipw_status' and typnamespace = 'public'::regnamespace) then
    create type public.local_ipw_status as enum ('calculated', 'deferred');
  end if;

  if not exists (select 1 from pg_type where typname = 'energy_confidence_quality' and typnamespace = 'public'::regnamespace) then
    create type public.energy_confidence_quality as enum ('unavailable', 'low', 'medium', 'high');
  end if;
end
$$;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  created_at timestamptz not null default now(),
  constraint profiles_display_name_length check (display_name is null or length(display_name) between 1 and 80)
);

comment on table public.profiles is 'Minimal user profile metadata for Telperia accounts. Authorization must not depend on user-editable metadata.';
comment on column public.profiles.user_id is 'References auth.users(id).';

create table if not exists public.result_uploads (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  storage_path text not null unique,
  package_sha256 text not null,
  run_id uuid not null,
  schema_version text not null,
  methodology_version text not null,
  evaluation_suite text not null,
  visibility public.result_visibility not null default 'private',
  ingestion_status public.ingestion_status not null default 'pending',
  validation_error text,
  validation_warnings text[] not null default '{}',
  public_submission_requested boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint result_uploads_package_sha256_format check (package_sha256 ~ '^[a-f0-9]{64}$'),
  constraint result_uploads_storage_path_shape check (storage_path ~ '^users/[0-9a-f-]{36}/runs/[0-9a-f-]{36}\.json$'),
  constraint result_uploads_schema_version check (schema_version = '0.1'),
  constraint result_uploads_methodology_version check (methodology_version = '0.1'),
  constraint result_uploads_evaluation_suite check (evaluation_suite = 'tci-v0.1'),
  constraint result_uploads_public_requires_acceptance check (visibility <> 'public' or ingestion_status = 'accepted')
);

comment on table public.result_uploads is 'Private owner-scoped upload records for raw Telperia result packages.';
comment on column public.result_uploads.storage_path is 'Private Storage path generated by the backend. Clients should not choose this value.';
comment on column public.result_uploads.package_sha256 is 'Hash of the canonical raw package used for duplicate detection.';
comment on column public.result_uploads.validation_warnings is 'Non-blocking validation warnings such as low_energy_confidence.';
comment on column public.result_uploads.ingestion_status is 'Set by trusted ingestion code after local validation. Client-side direct writes are intentionally not granted.';

create table if not exists public.model_configs (
  id uuid primary key default gen_random_uuid(),
  model_name text not null,
  model_revision text not null,
  quantization text not null,
  runtime_engine text not null,
  runtime_version text not null,
  created_at timestamptz not null default now(),
  constraint model_configs_runtime_engine check (runtime_engine = 'ollama'),
  constraint model_configs_identity_not_blank check (
    length(model_name) > 0
    and length(model_revision) > 0
    and length(quantization) > 0
    and length(runtime_version) > 0
  ),
  unique (model_name, model_revision, quantization, runtime_engine, runtime_version)
);

comment on table public.model_configs is 'Normalized model and runtime identity extracted from accepted result packages.';

create table if not exists public.hardware_profiles (
  id uuid primary key default gen_random_uuid(),
  gpu text not null,
  gpu_count integer not null,
  driver text not null,
  cuda text not null,
  system_ram_gb numeric not null,
  operating_system text not null,
  monitor_backend text not null,
  created_at timestamptz not null default now(),
  constraint hardware_profiles_gpu_count_positive check (gpu_count > 0),
  constraint hardware_profiles_ram_positive check (system_ram_gb > 0),
  constraint hardware_profiles_monitor_backend check (monitor_backend in ('disabled', 'nvml')),
  constraint hardware_profiles_identity_not_blank check (
    length(gpu) > 0
    and length(driver) > 0
    and length(cuda) > 0
    and length(operating_system) > 0
  ),
  unique (gpu, gpu_count, driver, cuda, system_ram_gb, operating_system, monitor_backend)
);

comment on table public.hardware_profiles is 'Public-safe local hardware metadata. Do not store hostnames, serial numbers, local usernames, or filenames.';

create table if not exists public.evaluation_runs (
  id uuid primary key default gen_random_uuid(),
  upload_id uuid not null references public.result_uploads(id) on delete cascade,
  model_config_id uuid not null references public.model_configs(id),
  hardware_profile_id uuid not null references public.hardware_profiles(id),
  run_id uuid not null unique,
  result_timestamp timestamptz not null,
  node_id text not null,
  schema_version text not null,
  methodology_version text not null,
  evaluation_suite text not null,
  completed_tasks integer not null,
  total_tasks integer not null,
  completion_ratio numeric not null,
  error_count integer not null,
  verification_level integer not null,
  runner_version text not null,
  is_public boolean not null default false,
  created_at timestamptz not null default now(),
  constraint evaluation_runs_task_counts check (completed_tasks >= 0 and total_tasks >= 0 and completed_tasks <= total_tasks),
  constraint evaluation_runs_completion_ratio check (completion_ratio >= 0 and completion_ratio <= 1),
  constraint evaluation_runs_error_count check (error_count >= 0),
  constraint evaluation_runs_verification_level check (verification_level between 0 and 4),
  constraint evaluation_runs_schema_version check (schema_version = '0.1'),
  constraint evaluation_runs_methodology_version check (methodology_version = '0.1'),
  constraint evaluation_runs_evaluation_suite check (evaluation_suite = 'tci-v0.1')
);

comment on table public.evaluation_runs is 'Queryable run summary extracted from an accepted raw result package.';
comment on column public.evaluation_runs.node_id is 'User-supplied runner node label. It is not a trusted device identifier.';
comment on column public.evaluation_runs.is_public is 'Set by trusted review flow. Public clients can read only approved public rows.';

create table if not exists public.run_scores (
  evaluation_run_id uuid primary key references public.evaluation_runs(id) on delete cascade,
  tci_v0_1 numeric not null,
  factual_correct_responses integer not null,
  factual_incorrect_responses integer not null,
  factual_abstentions integer not null,
  factual_total_questions integer not null,
  factual_correctness_rate numeric not null,
  factual_incorrect_answer_rate numeric not null,
  factual_abstention_rate numeric not null,
  factual_attempted_accuracy numeric not null,
  local_ipw_unscaled numeric,
  local_ipw_displayed numeric,
  local_ipw_status public.local_ipw_status not null,
  gpu_energy_wh numeric not null,
  average_power_w numeric not null,
  peak_power_w numeric not null,
  sampling_interval_ms integer not null,
  energy_source text not null,
  energy_scope text not null,
  energy_confidence public.energy_confidence_quality,
  energy_warning_codes text[] not null default '{}',
  tokens_per_second numeric not null,
  created_at timestamptz not null default now(),
  constraint run_scores_tci_range check (tci_v0_1 >= 0 and tci_v0_1 <= 100),
  constraint run_scores_factual_counts check (
    factual_correct_responses >= 0
    and factual_incorrect_responses >= 0
    and factual_abstentions >= 0
    and factual_total_questions >= 0
    and factual_correct_responses + factual_incorrect_responses + factual_abstentions = factual_total_questions
  ),
  constraint run_scores_factual_rates check (
    factual_correctness_rate between 0 and 1
    and factual_incorrect_answer_rate between 0 and 1
    and factual_abstention_rate between 0 and 1
    and factual_attempted_accuracy between 0 and 1
  ),
  constraint run_scores_ipw_shape check (
    (local_ipw_status = 'calculated' and local_ipw_unscaled is not null and local_ipw_displayed is not null and gpu_energy_wh > 0)
    or
    (local_ipw_status = 'deferred' and local_ipw_unscaled is null and local_ipw_displayed is null)
  ),
  constraint run_scores_energy_nonnegative check (
    gpu_energy_wh >= 0
    and average_power_w >= 0
    and peak_power_w >= 0
    and sampling_interval_ms > 0
    and tokens_per_second >= 0
  ),
  constraint run_scores_energy_scope check (energy_scope = 'local_inference_hardware'),
  constraint run_scores_energy_source check (energy_source in ('unavailable', 'local_gpu_telemetry'))
);

comment on table public.run_scores is 'Score, energy, and reliability summaries extracted from accepted result packages. Raw details remain in private Storage.';
comment on column public.run_scores.local_ipw_unscaled is 'Preserved unscaled Local IPW value.';
comment on column public.run_scores.local_ipw_displayed is 'Scaled display Local IPW value.';

create table if not exists public.public_submissions (
  id uuid primary key default gen_random_uuid(),
  evaluation_run_id uuid not null unique references public.evaluation_runs(id) on delete cascade,
  submitted_by uuid not null references auth.users(id) on delete cascade,
  status public.public_submission_status not null default 'pending_review',
  review_notes text,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  constraint public_submissions_reviewed_at check (
    (status = 'pending_review' and reviewed_at is null)
    or
    (status in ('approved', 'rejected') and reviewed_at is not null)
  )
);

comment on table public.public_submissions is 'Review queue for user-requested public Observatory submissions.';
comment on column public.public_submissions.review_notes is 'Reviewer notes. Do not store private prompt, response, or credential material here.';

